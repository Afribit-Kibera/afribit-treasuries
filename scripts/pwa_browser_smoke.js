// Run through playwright-cli run-code --filename after opening a fresh QA-run snapshot.
async (page) => {
  const checks = []
  const ensure = (condition, message) => { if (!condition) throw new Error(message); checks.push(message) }
  const textVisible = async text => { await page.getByText(text, { exact: true }).first().waitFor({ state: 'visible' }) }
  const close = async () => page.getByRole('button', { name: 'Close dialog', exact: true }).click()
  const nav = async name => page.getByRole('navigation').getByRole('button', { name, exact: true }).click()
  const viewAs = async persona => {
    await nav('Profile')
    await page.getByLabel('Viewing as').selectOption(persona)
    await page.waitForFunction(value => document.querySelector('#demo-member')?.value === value && !document.querySelector('#demo-member')?.disabled, persona)
    await nav('Home')
  }
  await textVisible('KES 42,500')
  ensure(await page.locator('.balance-number').textContent() === 'KES 42,500', 'Initial dashboard reconciles to seeded backend')
  const initialTheme = await page.locator('html').getAttribute('data-theme')
  await page.getByRole('button', { name: `Switch to ${initialTheme === 'dark' ? 'light' : 'dark'} mode` }).click()
  const changedTheme = await page.locator('html').getAttribute('data-theme')
  await page.reload()
  await textVisible('KES 42,500')
  ensure(await page.locator('html').getAttribute('data-theme') === changedTheme, 'Theme persists after reload')
  await page.getByRole('button', { name: 'Hide balance', exact: true }).click()
  ensure(await page.locator('.balance-number').textContent() === '••••••', 'Balance privacy control hides capital')
  await page.getByRole('button', { name: 'Show balance', exact: true }).click()
  await page.getByRole('button', { name: 'Reveal recent activity', exact: true }).click()
  ensure(await page.locator('.recent-activity .activity-row').count() === 4, 'Recent activity expands with backend events')
  await page.getByRole('button', { name: 'Hide recent activity', exact: true }).click()
  await nav('My Clan')
  ensure(await page.locator('.member-row').count() === 5, 'My Clan renders all five real fixture memberships')
  await nav('Activity')
  await page.getByRole('button', { name: 'Recovery', exact: true }).click()
  await textVisible('Every step forward starts somewhere.')
  ensure(await page.locator('.activity-row').count() === 0, 'Recovery filter has a meaningful empty state')
  await nav('Home')
  await page.getByRole('button', { name: 'Review request', exact: true }).click()
  await page.getByRole('button', { name: 'Approve request', exact: true }).click()
  await textVisible('2 of 3 votes')
  ensure(await page.getByRole('button', { name: 'Approve request', exact: true }).count() === 0, 'Member vote saved; duplicate voting action removed')
  await close()
  await viewAs('treasurer')
  await page.getByRole('button', { name: 'Review request', exact: true }).click()
  await page.getByRole('button', { name: 'Approve request', exact: true }).click()
  await textVisible('3 of 3 votes')
  await page.getByRole('button', { name: 'Demo: view as recipient' }).click()
  await page.getByRole('button', { name: 'Accept recovery terms', exact: true }).click()
  await textVisible('An eligible signatory can prepare this grant for approval.')
  checks.push('Separate member quorum and beneficiary acceptance completed')
  await close()
  await viewAs('chair')
  await page.getByRole('button', { name: 'Review request', exact: true }).click()
  await page.getByRole('button', { name: 'Prepare signatory approval', exact: true }).click()
  await page.getByRole('button', { name: 'Approve exact demo payment', exact: true }).click()
  await textVisible('1 of 2')
  ensure(await page.getByRole('button', { name: 'Complete demo grant', exact: true }).count() === 0, 'One signatory cannot issue the grant')
  await close()
  await viewAs('treasurer')
  await page.getByRole('button', { name: 'Review request', exact: true }).click()
  await page.getByRole('button', { name: 'Approve exact demo payment', exact: true }).click()
  await page.getByRole('button', { name: 'Complete demo grant', exact: true }).click()
  await textVisible('KES 8,000 remaining')
  checks.push('Second independent approval permits one backend simulated grant')
  await page.getByRole('button', { name: 'Demo: view as recipient' }).click()
  await page.getByRole('button', { name: 'Make a recovery payment', exact: true }).click()
  await page.getByLabel('Amount in Kenyan shillings').fill('100')
  await page.getByLabel('Recovery method').selectOption('otc')
  await page.getByRole('button', { name: 'Record demo recovery', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  ensure(await page.locator('.balance-number').textContent() === 'KES 34,599.95', 'OTC recovery raises treasury after the simulated fee')
  await page.getByRole('button', { name: 'Add a contribution, request, repayment or clan', exact: true }).click()
  await page.getByRole('button', { name: /^Contribute/ }).click()
  await page.getByLabel('Amount in Kenyan shillings').fill('500')
  await page.getByRole('button', { name: 'Record demo contribution', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  ensure(await page.locator('.balance-number').textContent() === 'KES 35,099.95', 'Contribution form credits the persisted simulated treasury')
  await page.getByRole('button', { name: 'Add a contribution, request, repayment or clan', exact: true }).click()
  await page.getByRole('button', { name: /^Request a grant/ }).click()
  await page.getByLabel('Amount in Kenyan shillings').fill('1000')
  await page.getByLabel('What will this make possible?').fill('Browser QA: new market stock')
  await page.getByRole('button', { name: 'Send request to your clan', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await textVisible('KES 1,000')
  checks.push('Grant request form creates a persisted member proposal')
  await page.getByRole('button', { name: 'Notifications', exact: true }).click()
  ensure(await page.locator('.notification-list > button').count() >= 1, 'Notifications open current pending grants')
  await close()
  await page.getByRole('button', { name: 'Add a contribution, request, repayment or clan', exact: true }).click()
  await page.getByRole('button', { name: /^Create a clan/ }).click()
  await page.getByLabel('Clan name').fill('Browser QA Seven Signers')
  await page.getByRole('button', { name: '7 signatories 4 approvals' }).click()
  await page.getByRole('button', { name: 'Create your clan', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await textVisible('Browser QA Seven Signers')
  await textVisible('4 approvals required')
  await textVisible('Your clan is created.')
  checks.push('Seven-signatory preset saves four-approval policy without a deposit')
  await page.setViewportSize({ width: 320, height: 740 })
  ensure(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Small viewport has no horizontal overflow')
  await page.screenshot({ path: 'output/playwright/clans-new-clan.png', scale: 'css' })
  const errors = await page.locator('[role="alert"]').count()
  ensure(errors === 0, 'No visible API error after complete browser flow')
  return { result: 'passed', checks, real_funds_moved: false, isolated_qa_run: true }
}
