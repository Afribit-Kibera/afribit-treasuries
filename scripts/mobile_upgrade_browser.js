async (page) => {
  const checks = [];
  const errors = [];
  const browser = page.context().browser();
  const context = await browser.newContext({ viewport: {width: 390, height: 844}, permissions: ['clipboard-read', 'clipboard-write'] });
  const p = await context.newPage();
  p.on('pageerror', error => errors.push(error.message));
  const cdp = await context.newCDPSession(p);
  await cdp.send('WebAuthn.enable');
  await cdp.send('WebAuthn.addVirtualAuthenticator', {options: {protocol: 'ctap2', transport: 'internal', hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true}});
  const check = (name, pass) => { if (!pass) throw new Error(name); checks.push(name); };
  await p.goto('http://localhost:8410');
  await p.getByRole('button', {name: 'Create my account', exact: true}).click();
  await p.getByRole('textbox', {name: 'Your name', exact: true}).fill('Mobile Review');
  const username = 'mobile_' + Date.now();
  await p.getByRole('textbox', {name: 'Choose a username', exact: true}).fill(username);
  await p.getByRole('textbox', {name: 'Phone number', exact: true}).fill('+254700000001');
  await p.locator('input[name="terms"]').check();
  await p.getByRole('button', {name: 'Continue to security'}).click();
  const registered = p.waitForResponse(response => response.url().endsWith('/api/auth/register/verify') && response.request().method() === 'POST');
  await p.getByRole('button', {name: 'Create my passkey', exact: true}).click();
  const kit = await (await registered).json();
  check('Real WebAuthn registration returns chosen username and 12 words', kit.handle === username && kit.recovery_codes.length === 1 && kit.recovery_codes[0].split(' ').length === 12);
  check('Recovery words have 12 numbered places', await p.locator('.recovery-word').count() === 12);
  await p.getByRole('checkbox', {name: 'I saved my username and 12 words.'}).check();
  await p.getByRole('button', {name: 'Continue to my account', exact: true}).click();
  await p.getByRole('button', {name: 'Create a clan', exact: true}).click();
  check('Phone setup is full screen', await p.locator('dialog').evaluate(el => Math.abs(el.getBoundingClientRect().height - innerHeight) < 2 && el.getBoundingClientRect().width === innerWidth));
  await p.getByRole('textbox', {name: 'Clan name', exact: true}).fill('Mobile Review Clan');
  check('Focused inputs are at least 16px', await p.getByRole('textbox', {name: 'Clan name', exact: true}).evaluate(el => parseFloat(getComputedStyle(el).fontSize) >= 16));
  await p.getByRole('textbox', {name: 'What brings you together?'}).fill('Testing our setup and recovery.');
  await p.getByRole('button', {name: 'Choose who approves'}).click();
  await p.getByRole('combobox', {name: 'Number of signatories'}).selectOption('3');
  await p.getByRole('checkbox', {name: 'I also choose to be one of the signatories.'}).check();
  await p.getByRole('checkbox', {name: 'I acknowledge these custody terms and will share them with members.'}).check();
  await p.getByRole('button', {name: 'Create Mobile Review Clan', exact: true}).click();
  await p.getByRole('heading', {name: 'Mobile Review Clan', exact: true}).waitFor();
  for (const width of [320, 390, 768, 1280]) {
    await p.setViewportSize({width, height: 844});
    check('No sideways page scroll at ' + width, await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  }
  await p.setViewportSize({width: 390, height: 844});
  await p.getByRole('button', {name: 'My Clan', exact: true}).click();
  await p.getByRole('button', {name: 'Invite', exact: true}).click();
  await p.getByRole('button', {name: 'Create private invitation', exact: true}).click();
  await p.getByRole('textbox', {name: 'Invitation link', exact: true}).waitFor();
  await p.getByRole('button', {name: 'Copy invitation', exact: true}).click();
  await p.getByRole('status').filter({hasText: 'copied'}).waitFor();
  check('Copy shows a visible confirmation and check mark', await p.locator('.copy-toast').isVisible() && await p.locator('.copy-button.is-copied').count() === 1);
  check('Copy preserves the invitation field', (await p.getByRole('textbox', {name: 'Invitation link', exact: true}).inputValue()).includes('/join#'));
  await p.getByRole('button', {name: 'Close dialog'}).click();
  await p.getByRole('button', {name: 'Profile', exact: true}).click();
  check('Active clan has no second clan or switch actions', await p.getByRole('button', {name: 'Create another clan', exact: true}).count() === 0 && await p.getByRole('button', {name: 'Switch clan', exact: true}).count() === 0);
  await p.getByRole('button', {name: 'Change username'}).click();
  await p.getByRole('textbox', {name: 'New username', exact: true}).fill(username + 'x');
  await p.getByRole('button', {name: 'Save with my passkey'}).click();
  await p.locator('.account-handle').filter({hasText: username + 'x'}).waitFor();
  check('Username change is signed with a passkey', true);
  await p.getByRole('button', {name: 'Sign out', exact: true}).click();
  await p.getByRole('button', {name: 'Lost access? Recover your account'}).click();
  await p.getByRole('textbox', {name: 'Username', exact: true}).fill(username + 'x');
  await p.getByRole('textbox', {name: 'Your 12 recovery words', exact: true}).fill(kit.recovery_codes[0]);
  await p.getByRole('button', {name: 'Create replacement passkey'}).click();
  await p.getByRole('checkbox', {name: 'I saved my username and 12 words.'}).check();
  await p.getByRole('button', {name: 'Continue to my account', exact: true}).click();
  await p.getByRole('heading', {name: 'Mobile Review Clan', exact: true}).waitFor();
  check('Word recovery returns the same clan', true);
  await p.getByRole('button', {name: 'Switch to light mode'}).click();
  await p.screenshot({path: 'output/playwright/clans-upgrade-mobile-light.png', fullPage: true});
  await p.getByRole('button', {name: 'Switch to dark mode'}).click();
  await p.screenshot({path: 'output/playwright/clans-upgrade-mobile-dark.png', fullPage: true});
  check('No browser errors', errors.length === 0);
  await context.close();
  return {checks, errors, environment: 'Loopback preview; real browser WebAuthn, disposable accounts', mainnet_funds_moved: false};
}
